/** Slovak mnemonic wordlist from rastislavcore/slovak-wordlist. */
export class LangSk extends Wordlist {
	constructor() {
		super("sk");
	}

	getWord(index: number): string {
		assertArgument(
			Number.isInteger(index) && index >= 0 && index < words.length,
			`invalid word index: ${index}`,
			"index",
			index,
		);
		return words[index];
	}

	getWordIndex(word: string): number {
		return words.indexOf(word);
	}

	static wordlist(): LangSk {
		if (wordlist == null) {
			wordlist = new LangSk();
		}
		return wordlist;
	}
}
